//! The cheat sheet on the website's CLI page (diri.sh/docs/cli/) is the
//! output of `dirijor help --markdown`, which renders the same command tree
//! as `--help` and the shell completions. This keeps the page from drifting.
//!
//! Regenerate after changing a command: `DIRI_UPDATE_DOCS=1 cargo test -p dirijor-mcp --test cli_docs`,
//! then `node website/scripts/site.mjs`.

use std::path::Path;
use std::process::Command;

const START: &str = "<!-- generated by `dirijor help --markdown`: start -->\n";
const END: &str = "<!-- generated by `dirijor help --markdown`: end -->";

#[test]
fn website_cheat_sheet_matches_the_command_tree() {
    let page = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../../website/docs-src/cli.md");
    let output = Command::new(env!("CARGO_BIN_EXE_dirijor"))
        .args(["help", "--markdown"])
        .output()
        .unwrap();
    assert!(output.status.success());
    let sheet = String::from_utf8(output.stdout).unwrap();
    let text = std::fs::read_to_string(&page).unwrap();
    let start = text
        .find(START)
        .expect("cheat sheet start marker in cli.md")
        + START.len();
    let end = text.find(END).expect("cheat sheet end marker in cli.md");
    if std::env::var_os("DIRI_UPDATE_DOCS").is_some() {
        std::fs::write(&page, format!("{}{sheet}{}", &text[..start], &text[end..])).unwrap();
        return;
    }
    assert_eq!(
        text[start..end],
        sheet,
        "website/docs-src/cli.md cheat sheet is stale. Run: DIRI_UPDATE_DOCS=1 cargo test -p dirijor-mcp --test cli_docs"
    );
}

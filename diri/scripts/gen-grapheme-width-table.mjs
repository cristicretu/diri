#!/usr/bin/env node
// Regenerates vendor/alacritty_terminal/src/term/grapheme_table.rs from Bun's
// src/jsc/bindings/stringWidthTables.h, so terminal cell widths follow the
// `Bun.stringWidth` that Claude Code lays out its screen with.
//
//   node scripts/gen-grapheme-width-table.mjs <path/to/stringWidthTables.h> <bun version>
//
// Fetch the header for the Bun release the current Claude Code embeds
// (`strings $(readlink -f $(which claude)) | grep -o 'Bun v1[.0-9]*'`):
//   https://raw.githubusercontent.com/oven-sh/bun/bun-v<version>/src/jsc/bindings/stringWidthTables.h
// Each byte packs the grapheme break class (bits 0-4), the width class
// (bits 5-6: zero, narrow, wide, ambiguous) and the Emoji property (bit 7).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const [headerPath, bunVersion] = process.argv.slice(2);
if (!headerPath || !bunVersion) throw new Error("usage: gen-grapheme-width-table.mjs <stringWidthTables.h> <bun version>");
const header = readFileSync(headerPath, "utf8");
const unicode = header.match(/from the Unicode\s*\/\/\s*([0-9.]+) Character Database/)?.[1] ?? "unknown";
const parse = name => {
  const m = header.match(new RegExp(`${name}\\[[0-9]*\\] = \\{([\\s\\S]*?)\\n\\};`));
  if (!m) throw new Error(`missing ${name}`);
  return m[1].split(/[,\s]+/).filter(t => /^\d+$/.test(t)).map(Number);
};
const [s1, s2, s3] = ["kGraphemeBreakStage1", "kGraphemeBreakStage2", "kGraphemeBreakStage3"].map(parse);
const packed = cp => s3[s2[s1[cp >> 8] + (cp & 0xff)]];

const blocks = [], index = new Map(), stage1 = [];
for (let hi = 0; hi < 0x1100; hi++) {
  const block = Array.from({ length: 256 }, (_, lo) => packed((hi << 8) | lo));
  const key = block.join(",");
  if (!index.has(key)) { index.set(key, blocks.length); blocks.push(block); }
  stage1.push(index.get(key));
}
if (blocks.length > 256) throw new Error(`${blocks.length} blocks do not fit a u8 index`);
// Spot checks against Bun's own static_asserts.
const width = cp => (packed(cp) >> 5) & 3;
for (const [cp, w] of [[0x41, 1], [0xad, 0], [0x4e2d, 2], [0xa7, 3], [0x1161, 0], [0x1112, 2]])
  if (width(cp) !== w) throw new Error(`width of U+${cp.toString(16)} is ${width(cp)}, expected ${w}`);
if (!(packed(0x1f600) & 0x80) || packed(0x23) & 0x80) throw new Error("emoji bit check failed");

const rows = (values, per) => {
  const out = [];
  for (let i = 0; i < values.length; i += per) out.push("    " + values.slice(i, i + per).join(", ") + ",");
  return out.join("\n");
};
const text = `// Generated by diri/scripts/gen-grapheme-width-table.mjs from Bun v${bunVersion}
// src/jsc/bindings/stringWidthTables.h (Unicode ${unicode}). Do not edit by hand.
//
// Bun is MIT licensed; the classification derives from the Unicode Character
// Database. Each byte packs the grapheme break class (bits 0-4), the width
// class (bits 5-6: zero, narrow, wide, East Asian ambiguous) and the Emoji
// property with Bun's presentation early-outs (bit 7).

/// \`STAGE1[cp >> 8]\` is the block of \`cp\` in [\`STAGE2\`].
#[rustfmt::skip]
pub(super) static STAGE1: [u8; ${stage1.length}] = [
${rows(stage1, 32)}
];

/// Packed classification bytes, 256 per block.
#[rustfmt::skip]
pub(super) static STAGE2: [u8; ${blocks.length * 256}] = [
${rows(blocks.flat(), 32)}
];
`;
const out = join(dirname(fileURLToPath(import.meta.url)), "../vendor/alacritty_terminal/src/term/grapheme_table.rs");
writeFileSync(out, text);
console.log(`wrote ${out}: ${blocks.length} blocks, ${stage1.length + blocks.length * 256} bytes`);
